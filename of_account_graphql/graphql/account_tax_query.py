import graphene

from odoo.addons.of_graphql.graphql.odoo_domain import OdooDomainInput
from odoo.addons.of_graphql.graphql.odoo_type import graphqlOdooDomain

from .account_tax_type import AccountTax, AccountTaxFilterInput


class AccountTaxQuery(graphene.ObjectType):
    _name = 'AccountTaxQuery'
    _type = 'query'

    account_taxs = graphene.List(
        graphene.NonNull(AccountTax),
        filter=graphene.Argument(AccountTaxFilterInput),
        domain=graphene.List(graphene.NonNull(OdooDomainInput)),
        limit=graphene.Int(),
        offset=graphene.Int(),
    )

    @staticmethod
    def resolve_account_taxs(root, info, filter=None, domain=None, offset=0, limit=10):
        env = info.context["env"]
        odoo_domain = []
        odoo_type = {
            'id': 'int',
        }
        if domain:
            odoo_domain = graphqlOdooDomain(odoo_type, domain)

        if filter:
            if filter.id:
                odoo_domain += [('id', '=', filter.id)]
            if filter.name:
                odoo_domain += [('name', 'like', filter.name)]

        return env['account.tax'].search(odoo_domain, offset=offset, limit=limit)
